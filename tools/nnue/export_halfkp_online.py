"""Export the frozen HalfKP Stage 3 artifact for CPU-only search."""

from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import lzma
from pathlib import Path

import numpy as np

from .halfkp_features import FEATURES
from .halfkp_model import load_weights


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_WEIGHTS = ROOT / "tools/nnue/runs/halfkp_v1/stage3.npz"
DEFAULT_OUTPUT = ROOT / "Team19_halfkp_weights.py"
EXPECTED_SHA256 = "ac066d3d7ca78b496ab6b6d03987825f7542422bdd77395fa67e08f8efc393bf"
REFINEMENT = 2048


def _int16_planes(values: np.ndarray) -> bytes:
    return values.astype("<i2").view(np.uint8).reshape(-1, 2).T.tobytes()


def _pack(weights: dict[str, np.ndarray]) -> bytes:
    embedding = weights["embedding"]
    peak = np.abs(embedding).max(axis=1)
    scales = np.where(peak > 0, peak / np.float32(32767), np.float32(1.0))
    coarse = np.rint(embedding / scales[:, None])
    # A second fixed-point plane preserves the search residual to under 5e-4.
    # Both planes are decoded only once; the search reads ordinary float32 rows.
    fine = np.rint((embedding - coarse * scales[:, None]) /
                   (scales[:, None] / np.float32(REFINEMENT)))
    arrays = (
        weights["acc_bias"], weights["hidden2_weight"].T, weights["hidden2_bias"],
        weights["head_weight"], weights["head_bias"],
    )
    return b"".join((scales.astype("<f4").tobytes(),
                     _int16_planes(coarse), _int16_planes(fine),
                     *(array.astype("<f4").tobytes() for array in arrays)))


def render(weights: dict[str, np.ndarray], source_hash: str) -> str:
    if (weights["embedding"].shape != (FEATURES, 64)
            or int(weights["hidden2"]) != 32 or float(weights["residual_clip"]) != 750.0
            or float(weights["eval_scale"]) != 6000.0):
        raise ValueError("Expected the sealed 13122 -> 64 -> 32 -> 2 HalfKP Stage 3 model")
    encoded = base64.b64encode(lzma.compress(_pack(weights))).decode("ascii")
    literal = "\n".join(f"    b{encoded[start:start + 108]!r}"
                        for start in range(0, len(encoded), 108))
    return f'''"""Compressed HalfKP Stage 3 parameters generated by export_halfkp_online.

Source stage3.npz SHA-256: {source_hash}
Heads are D (0) and A (1), both attacker-positive. W2 is stored input-major.
The int16 embedding and its low-bit correction share one float32 scale per row.
"""

from base64 import b64decode
from functools import lru_cache
from lzma import decompress

import numpy as np

SOURCE_SHA256 = {source_hash!r}
RESIDUAL_CLIP = np.float32(750.0)
EVAL_SCALE = np.float32(6000.0)
_FEATURES = {FEATURES}
_HIDDEN = 64
_REFINEMENT = np.float32({REFINEMENT})

_PACKED = (
{literal}
)


@lru_cache(maxsize=1)
def load_weights():
    """Decode the parameters once per process, on first opt-in construction."""
    packet = decompress(b64decode(_PACKED))
    scales = np.frombuffer(packet, dtype="<f4", count=_FEATURES)
    size = _FEATURES * _HIDDEN
    offset = scales.nbytes

    def plane(start):
        encoded = np.frombuffer(packet, dtype=np.uint8, count=2 * size, offset=start)
        interleaved = np.ascontiguousarray(encoded.reshape(2, size).T)
        return interleaved.view("<i2").reshape(_FEATURES, _HIDDEN).astype(np.float32)

    embedding = plane(offset)
    embedding *= scales[:, None]
    correction = plane(offset + 2 * size)
    correction *= scales[:, None] / _REFINEMENT
    embedding += correction
    embedding.flags.writeable = False
    offset += 4 * size
    # b1, input-major W2, b2, D/A heads and head bias in one contiguous block.
    small = np.frombuffer(packet, dtype="<f4", offset=offset)
    storage = np.empty(len(small) + 15, dtype=np.float32)
    aligned = (-storage.ctypes.data % 64) // storage.itemsize
    parameters = storage[aligned:aligned + len(small)]
    parameters[:] = small
    parameters.flags.writeable = False
    return embedding, parameters
'''


def verify_module(path: Path, weights: dict[str, np.ndarray]) -> float:
    spec = importlib.util.spec_from_file_location("_halfkp_weight_verification", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    actual = module.load_weights()
    small = (weights["acc_bias"], weights["hidden2_weight"].T, weights["hidden2_bias"],
             weights["head_weight"], weights["head_bias"])
    expected = np.concatenate([array.ravel() for array in small])
    if any(not a.flags.c_contiguous or a.flags.writeable for a in actual):
        raise ValueError("Generated weight arrays must be contiguous and read-only")
    if not np.array_equal(actual[1], expected):
        raise ValueError("The small float32 tensors must survive the export bit for bit")
    if actual[1].ctypes.data % 64:
        raise ValueError("The second-layer coefficient block must be cache-line aligned")
    if (module.SOURCE_SHA256 != EXPECTED_SHA256
            or module.RESIDUAL_CLIP != weights["residual_clip"]
            or module.EVAL_SCALE != weights["eval_scale"]):
        raise ValueError("The generated module has incorrect source, bound or scaling metadata")
    return float(np.max(np.abs(actual[0] - weights["embedding"])))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--weights", type=Path, default=DEFAULT_WEIGHTS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    digest = hashlib.sha256(args.weights.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError(f"Unexpected HalfKP Stage 3 SHA-256: {digest}")
    weights = load_weights(args.weights)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_name(args.output.stem + ".tmp.py")
    temporary.write_text(render(weights, digest), encoding="utf-8", newline="\n")
    try:
        error = verify_module(temporary, weights)
        if error > 2e-8:
            raise ValueError(f"Embedding quantization error is too large: {error}")
        temporary.replace(args.output)
    finally:
        temporary.unlink(missing_ok=True)
    size = args.output.stat().st_size
    output_digest = hashlib.sha256(args.output.read_bytes()).hexdigest()
    print(f"exported={args.output} bytes={size} sha256={output_digest}")
    print(f"source_sha256={digest} max_abs_embedding_error={error:.9g}")


if __name__ == "__main__":
    main()
